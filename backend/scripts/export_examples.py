"""Export one real JSON response per endpoint into contract_examples/.

Run from the backend directory:  python scripts/export_examples.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_DIR))

from fastapi.testclient import TestClient  # noqa: E402

from app.config import DEMO_DIR  # noqa: E402
from app.main import app  # noqa: E402

OUTPUT_DIR = BACKEND_DIR / "contract_examples"


def save(name: str, payload) -> None:
    path = OUTPUT_DIR / name
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {path.name} ({len(json.dumps(payload))} bytes)")


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    with TestClient(app) as client:
        save("health.json", client.get("/api/health").json())

        demo = client.post("/api/demo/generate", json={"industry": "fashion"}).json()
        save("demo-generate.json", demo)
        dataset_id = demo["datasetId"]

        sample = (DEMO_DIR / "orders.csv").read_bytes()
        upload = client.post(
            "/api/upload",
            files=[("files", ("orders_sample.csv", sample, "text/csv"))],
        )
        if upload.status_code != 200:
            raise SystemExit(f"upload failed: {upload.status_code} {upload.text}")
        save("upload.json", upload.json())

        mapping = {"files": [entry["suggestedMapping"] for entry in demo["files"]]}
        mapped = client.post("/api/map-schema", json={"datasetId": dataset_id, "mapping": mapping})
        if mapped.status_code != 200:
            raise SystemExit(f"map-schema failed: {mapped.status_code} {mapped.text}")
        save("map-schema.json", mapped.json())

        save("analyze.json", client.post(f"/api/analyze/{dataset_id}").json())
        save("progress.json", client.get(f"/api/progress/{dataset_id}").json())
        save("quality.json", client.get(f"/api/quality/{dataset_id}").json())

        overview = client.get(f"/api/overview/{dataset_id}").json()
        save("overview.json", overview)

        if overview["filters"]["couriers"]:
            filtered = client.get(
                f"/api/overview/{dataset_id}",
                params={"courier": overview["filters"]["couriers"][0]},
            ).json()
            save("overview-filtered.json", filtered)

        findings = client.get(f"/api/findings/{dataset_id}").json()
        if not findings:
            raise SystemExit("no findings produced by the demo dataset")
        save("findings.json", findings)

        first = findings[0]
        save("finding.json", client.get(f"/api/findings/{dataset_id}/{first['id']}").json())

        decision = client.post(
            f"/api/findings/{dataset_id}/{first['id']}/decision",
            json={"decision": "approve", "note": "Assign to the operations lead for review."},
        )
        save("decision.json", decision.json())

        second = findings[1] if len(findings) > 1 else findings[0]
        status = client.patch(
            f"/api/findings/{dataset_id}/{second['id']}/status",
            json={"status": "investigating"},
        )
        save("status.json", status.json())

        task = client.post(
            f"/api/findings/{dataset_id}/{first['id']}/task",
            json={"title": "Review the flagged route with the carrier"},
        )
        save("task.json", task.json())

        save("actions.json", client.get(f"/api/actions/{dataset_id}").json())
        save("report.json", client.post(f"/api/report/{dataset_id}").json())

    readme = [
        "# Contract examples",
        "",
        "One real response per endpoint, generated by `scripts/export_examples.py` against the demo dataset.",
        "",
        "| Endpoint | File |",
        "| --- | --- |",
        "| `GET /api/health` | `health.json` |",
        "| `POST /api/demo/generate` | `demo-generate.json` |",
        "| `POST /api/upload` | `upload.json` |",
        "| `POST /api/map-schema` | `map-schema.json` |",
        "| `POST /api/analyze/:id` | `analyze.json` |",
        "| `GET /api/progress/:id` | `progress.json` |",
        "| `GET /api/quality/:id` | `quality.json` |",
        "| `GET /api/overview/:id` | `overview.json`, `overview-filtered.json` |",
        "| `GET /api/findings/:id` | `findings.json` |",
        "| `GET /api/findings/:id/:findingId` | `finding.json` |",
        "| `POST /api/findings/:id/:findingId/decision` | `decision.json` |",
        "| `PATCH /api/findings/:id/:findingId/status` | `status.json` |",
        "| `POST /api/findings/:id/:findingId/task` | `task.json` |",
        "| `GET /api/actions/:id` | `actions.json` |",
        "| `POST /api/report/:id` | `report.json` |",
        "",
    ]
    (OUTPUT_DIR / "README.md").write_text("\n".join(readme), encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main()
